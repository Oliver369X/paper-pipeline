"""Research and code packs for external review (zip-ready folders)."""

from __future__ import annotations

import logging
import shutil
import subprocess
from pathlib import Path

logger = logging.getLogger(__name__)

_RESEARCH_REL = [
    "draft_paper.md",
    "evidence/claims.json",
    "validation/quality_validation.json",
    "triage/triage_report.json",
    "evidence/evidence_index.json",
    "publication/publish_decision.json",
    "objective_state.json",
    "goal_selection.json",
    "goals.json",
    "safety_trace.jsonl",
    "agent_decisions.jsonl",
    "perplexity_call_record.jsonl",
]


def build_research_pack(output_dir: Path) -> Path:
    """Copy key artifacts into ``outputs/research_pack/`` (overwrite-safe)."""

    dest = output_dir / "research_pack"
    if dest.exists():
        shutil.rmtree(dest)
    dest.mkdir(parents=True)

    for rel in _RESEARCH_REL:
        src = output_dir / rel
        if not src.is_file():
            continue
        out = dest / rel
        out.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(src, out)
    return dest


def build_code_pack_manifest(output_dir: Path, repo_root: Path | None = None) -> Path:
    """Write ``outputs/code_pack/MANIFEST.md`` with optional ``git rev-parse HEAD``."""

    pack_dir = output_dir / "code_pack"
    pack_dir.mkdir(parents=True, exist_ok=True)
    sha = ""
    root = repo_root or output_dir
    while root != root.parent:
        git_dir = root / ".git"
        if git_dir.exists():
            try:
                out = subprocess.run(
                    ["git", "rev-parse", "HEAD"],
                    cwd=root,
                    capture_output=True,
                    text=True,
                    timeout=10,
                    check=False,
                )
                if out.returncode == 0:
                    sha = out.stdout.strip()
            except (OSError, subprocess.SubprocessError):
                pass
            break
        root = root.parent

    lines = [
        "# Code pack manifest",
        "",
        "Generated by `paper_pipeline.publication.packs.build_code_pack_manifest`.",
        "",
        f"- `git HEAD`: `{sha or 'unavailable'}`",
        f"- `output_dir`: `{output_dir.resolve()}`",
        "",
        "Zip example (from repo root):",
        "",
        "```bash",
        f"cd {output_dir.as_posix()} && zip -r code_pack.zip code_pack/",
        "```",
        "",
    ]
    man = pack_dir / "MANIFEST.md"
    man.write_text("\n".join(lines), encoding="utf-8")
    return man
