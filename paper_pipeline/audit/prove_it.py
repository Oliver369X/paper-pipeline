"""ProveIt notebook generator -- reproducibility audit for experiment claims.

Generates a Jupyter notebook that independently verifies claimed metrics
by loading artifacts, running blind evaluation, and computing statistical
significance.  Accompanied by a Makefile for one-command execution.
"""

from __future__ import annotations

import textwrap
from dataclasses import dataclass, field
from pathlib import Path
from typing import Optional

import nbformat
from nbformat.v4 import new_code_cell, new_markdown_cell, new_notebook


# ---------------------------------------------------------------------------
# Data model
# ---------------------------------------------------------------------------

@dataclass
class ExperimentMetadata:
    """All information needed to reproduce and verify an experiment."""

    exp_id: str
    topic: str
    model_artifact_path: str
    test_data_path: str
    target_metric: str
    claimed_metric_value: float
    sota_baseline: float
    model_weights_in_colab: bool = False
    colab_notebook_url: Optional[str] = None


# ---------------------------------------------------------------------------
# Makefile template
# ---------------------------------------------------------------------------

MAKEFILE_TEMPLATE: str = textwrap.dedent("""\
    # Auto-generated Makefile for experiment audit
    # Experiment: {exp_id}

    NOTEBOOK := {notebook_filename}
    VENV     := .venv

    .PHONY: setup verify_results clean publish_results

    setup:
    \tpython -m venv $(VENV)
    \t$(VENV)/bin/pip install -r requirements.txt
    \t@echo "[SETUP] Environment ready."

    verify_results: setup
    \tjupyter nbconvert --to notebook --execute $(NOTEBOOK) --output executed_$(NOTEBOOK)
    \t@echo "[VERIFY] Notebook executed. Check executed_$(NOTEBOOK) for results."

    clean:
    \trm -rf $(VENV) executed_*.ipynb __pycache__ .ipynb_checkpoints
    \t@echo "[CLEAN] Artifacts removed."

    publish_results:
    \t@echo "[PUBLISH] Uploading results..."
    \t@echo "TODO: integrate with your artifact store (S3, GCS, HuggingFace Hub, etc.)"
""")


# ---------------------------------------------------------------------------
# Notebook generator
# ---------------------------------------------------------------------------

class ProveItNotebookGenerator:
    """Builds a Jupyter notebook that audits a single experiment claim."""

    NBFORMAT_VERSION = 4

    def __init__(self, output_dir: Path) -> None:
        self.output_dir = Path(output_dir)
        self.output_dir.mkdir(parents=True, exist_ok=True)

    # -- public API ---------------------------------------------------------

    def generate(self, metadata: ExperimentMetadata) -> Path:
        """Create a *prove-it* notebook and write it to disk.

        Returns the path to the saved ``.ipynb`` file.
        """
        nb = new_notebook()
        nb.cells = self._build_cells(metadata)
        nbformat.validate(nb)

        filename = f"prove_it_{metadata.exp_id}.ipynb"
        dest = self.output_dir / filename
        with open(dest, "w", encoding="utf-8") as fh:
            nbformat.write(nb, fh)
        return dest

    # -- private helpers ----------------------------------------------------

    def _build_cells(self, m: ExperimentMetadata) -> list:
        """Return the ordered list of notebook cells."""
        cells: list = []

        cells.append(self._header_cell(m))
        cells.append(self._env_setup_cell(m))

        if m.model_weights_in_colab:
            cells.append(self._colab_download_cell(m))

        cells.append(self._load_artifacts_cell(m))
        cells.append(self._blind_eval_cell(m))
        cells.append(self._claim_verification_cell(m))
        cells.append(self._failure_cases_cell(m))
        cells.append(self._statistical_significance_cell(m))
        cells.append(self._human_decision_cell(m))

        return cells

    # -- individual cell builders -------------------------------------------

