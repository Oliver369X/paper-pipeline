# ---------------------------------------------------------------------------
# Full audit package
# ---------------------------------------------------------------------------

def generate_full_audit_package(
    metadata: ExperimentMetadata,
    output_dir: Path,
) -> dict[str, Path]:
    """Generate a complete audit package (notebook + Makefile).

    Returns a dict with keys ``"notebook"`` and ``"makefile"`` pointing to
    the generated file paths.
    """
    output_dir = Path(output_dir)
    output_dir.mkdir(parents=True, exist_ok=True)

    generator = ProveItNotebookGenerator(output_dir)
    notebook_path = generator.generate(metadata)

    makefile_content = MAKEFILE_TEMPLATE.format(
        exp_id=metadata.exp_id,
        notebook_filename=notebook_path.name,
    )
    makefile_path = output_dir / "Makefile"
    makefile_path.write_text(makefile_content, encoding="utf-8")

    return {
        "notebook": notebook_path,
        "makefile": makefile_path,
    }
